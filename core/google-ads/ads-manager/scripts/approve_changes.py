def interactive_mode(changes: list):
    """Interactive review mode."""
    if not changes:
        print("\n  No pending changes to review.")
        return

    print("\n  INTERACTIVE REVIEW MODE")
    print("  Commands: (a)pprove, (r)eject, (s)kip, (q)uit\n")

    remaining = changes.copy()

    for i, change in enumerate(changes):
        print("-" * 60)
        print(f"\n  Change {i+1} of {len(changes)}:")

        change_type = change.get("type", "unknown").upper()
        keyword = change.get("keyword") or change.get("search_term", "N/A")

        print(f"    Type: {change_type}")
        print(f"    Keyword/Term: {keyword}")
        print(f"    Reason: {change.get('reason', 'N/A')}")
        print()

        while True:
            action = input("  Action [a/r/s/q]: ").strip().lower()

            if action == "a":
                print("  Approving and applying...")
                success = apply_change(change)
                save_to_history(change, "approved" if success else "failed")
                remaining.remove(change)
                break

            elif action == "r":
                print("  Rejected.")
                save_to_history(change, "rejected")
                remaining.remove(change)
                break

            elif action == "s":
                print("  Skipped.")
                break

            elif action == "q":
                print("\n  Saving remaining changes and exiting...")
                save_pending_changes(remaining)
                return

            else:
                print("  Invalid input. Use: a (approve), r (reject), s (skip), q (quit)")

    save_pending_changes(remaining)
    print(f"\n  Review complete. {len(remaining)} changes remaining.")


def main():
    parser = argparse.ArgumentParser(description="Approve/reject pending Google Ads changes")
    parser.add_argument("--list", action="store_true", help="List pending changes")
    parser.add_argument("--approve", type=int, metavar="ID", help="Approve change by index")
    parser.add_argument("--reject", type=int, metavar="ID", help="Reject change by index")
    parser.add_argument("--approve-all", action="store_true", help="Approve all pending")
    parser.add_argument("--reject-all", action="store_true", help="Reject all pending")
    parser.add_argument("--clear", action="store_true", help="Clear all pending changes")
    args = parser.parse_args()

    print("\n" + "="*60)
    print("GOOGLE ADS CHANGE APPROVAL")
    print("="*60)

    changes = load_pending_changes()

    if args.list:
        list_pending_changes(changes)

    elif args.clear:
        save_pending_changes([])
        print("\n  All pending changes cleared.")

    elif args.approve is not None:
        if 0 <= args.approve < len(changes):
            change = changes[args.approve]
            print(f"\n  Approving change {args.approve}...")
            success = apply_change(change)
            save_to_history(change, "approved" if success else "failed")
            changes.pop(args.approve)
            save_pending_changes(changes)
        else:
            print(f"\n  Invalid index: {args.approve}")

    elif args.reject is not None:
        if 0 <= args.reject < len(changes):
            change = changes[args.reject]
            print(f"\n  Rejecting change {args.reject}...")
            save_to_history(change, "rejected")
            changes.pop(args.reject)
            save_pending_changes(changes)
        else:
            print(f"\n  Invalid index: {args.reject}")

    elif args.approve_all:
        print(f"\n  Approving all {len(changes)} changes...")
        for change in changes:
            success = apply_change(change)
            save_to_history(change, "approved" if success else "failed")
        save_pending_changes([])
        print("  All changes processed.")

    elif args.reject_all:
        print(f"\n  Rejecting all {len(changes)} changes...")
        for change in changes:
            save_to_history(change, "rejected")
        save_pending_changes([])
        print("  All changes rejected.")

    else:
        # Default: interactive mode
        list_pending_changes(changes)
        if changes:
            print("\n  Enter interactive mode? (y/n): ", end="")
            if input().strip().lower() == "y":
                interactive_mode(changes)

    print()


if __name__ == "__main__":
    main()
